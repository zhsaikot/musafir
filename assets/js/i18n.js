class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('musafir_lang') || 'en';
    document.documentElement.lang = this.currentLang;
  }

  getLang() {
    return this.currentLang;
  }

  setLang(lang) {
    if (lang !== 'en' && lang !== 'bn') lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('musafir_lang', lang);
    document.documentElement.lang = lang;
    this.translateDOM();
    window.dispatchEvent(new CustomEvent('musafir:lang-changed', { detail: { lang } }));
  }

  toggle() {
    const nextLang = this.currentLang === 'en' ? 'bn' : 'en';
    this.setLang(nextLang);
    return nextLang;
  }

  t(key) {
    const dict = window.TRANSLATIONS[this.currentLang] || window.TRANSLATIONS.en;
    if (dict && dict[key] !== undefined) return dict[key];
    if (window.TRANSLATIONS.en && window.TRANSLATIONS.en[key] !== undefined) return window.TRANSLATIONS.en[key];
    return null; // Return null so fallback does not overwrite existing HTML with raw key!
  }

  translateDOM() {
    // Translate all elements with data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation !== null) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.setAttribute('placeholder', translation);
        } else {
          el.innerHTML = translation;
        }
      }
    });

    // Update language switch button text (Compact luxury switch)
    const langBtnTexts = document.querySelectorAll('.lang-btn-text');
    langBtnTexts.forEach(btn => {
      btn.textContent = this.currentLang === 'en' ? 'বাং' : 'EN';
    });

    // Toggle Bengali font class on body
    if (this.currentLang === 'bn') {
      document.body.classList.add('font-bn');
    } else {
      document.body.classList.remove('font-bn');
    }
  }
}

window.i18n = new I18nManager();
document.addEventListener('DOMContentLoaded', () => {
  window.i18n.translateDOM();
});
